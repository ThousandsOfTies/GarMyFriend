const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createSimulatorServer } = require('../simulation/server.cjs');
const root = path.resolve(__dirname, '..');
const outputs = path.join(root, 'test-results');
fs.mkdirSync(outputs, { recursive: true });
const server = createSimulatorServer();
let serverClosed = false;
const listen = () => new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
const close = () => new Promise(resolve => { server.closeAllConnections?.(); server.close(resolve); serverClosed = true; });

(async () => {
  await listen();
  const url = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const state = () => page.evaluate(async () => (await fetch('/api/state')).json());
    const command = command => page.evaluate(async command => {
      const response = await fetch('/api/command', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(command) });
      if (!response.ok) throw new Error(await response.text());
      return response.json();
    }, command);
    const pixels = () => page.locator('#screen').evaluate(display => display.displayContext.canvas.toDataURL());
    const changeRange = async (id, value) => {
      await page.locator(`#${id}`).evaluate((input, value) => {
        input.value = String(value); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true }));
      }, value);
    };
    await page.goto(url);
    await page.waitForSelector('#connection.online');
    await page.waitForSelector('[data-scenario="greeting"]');
    assert.equal(await page.locator('[data-expression]').count(), 8);
    assert.equal(await page.locator('gar-sg90').count(), 6);
    const rotary=page.locator('#expression-rotary');
    await rotary.getByRole('button',{name:'Rotate clockwise',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#rotary-expression').textContent==='喜び');
    assert.equal((await state()).inputs.rotary.counter,1);
    await rotary.getByRole('button',{name:'Rotate counter-clockwise',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#rotary-expression').textContent==='通常');
    await rotary.getByRole('button',{name:'Press rotary encoder',exact:true}).focus();
    await page.keyboard.press('ArrowLeft');
    await page.waitForFunction(()=>document.querySelector('#rotary-expression').textContent==='ウインク');
    await rotary.getByRole('button',{name:'まばたき',exact:true}).click();
    await page.waitForTimeout(100);
    assert.ok((await state()).events.some(event=>event.message==='まばたき'));
    await command({type:'reset'});await page.waitForTimeout(150);
    await page.locator('#auto-blink').uncheck();
    const neutral = await pixels();
    await page.locator('[data-expression="happy"]').click();
    await page.waitForFunction(() => document.querySelector('#expression-name').textContent === '喜び');
    await page.waitForTimeout(650);
    assert.notEqual(await pixels(), neutral, 'Server expression must change display pixels.');
    await page.locator('#pause').click();
    await page.waitForFunction(() => document.querySelector('#pause').textContent === '再生');
    const paused = await pixels();
    const pausedTime = (await state()).timeMs;
    await page.waitForTimeout(250);
    assert.equal(await pixels(), paused, 'Pause must freeze face pixels.');
    assert.equal((await state()).timeMs, pausedTime, 'Pause must freeze authoritative simulation time.');
    await page.locator('#step').click();
    await page.waitForFunction(expected => Number.parseFloat(document.querySelector('#clock').textContent.replace(':', '')) > 0 || expected === 0, pausedTime);
    await page.waitForTimeout(120);
    assert.equal((await state()).timeMs, pausedTime + 100);
    await page.locator('#pause').click();
    await changeRange('gaze-x', 8);
    await page.waitForTimeout(200);
    assert.equal((await state()).motion.gazeX, 8);
    assert.notEqual(await pixels(), paused, 'Gaze must reach the actual display renderer.');
    await changeRange('joint-leftHip', 30);
    await page.waitForTimeout(600);
    const jointState = (await state()).joints.find(joint => joint.id === 'leftHip');
    assert.equal(jointState.angle, 30);
    const pwm = await page.locator('#virtual-pwm').evaluate(controller => controller.state);
    assert.ok(pwm.channels[0].off > pwm.channels[1].off, 'Shared servo component must receive changed PWM state.');
    await page.locator('#stop').click();
    await page.waitForSelector('body.stopped');
    assert.equal(await page.locator('#joint-leftHip').isDisabled(), true);
    assert.equal(await page.locator('#import').isDisabled(), true);
    assert.equal(await page.locator('[data-scenario="greeting"]').isDisabled(), true);
    const stoppedAngles = (await state()).joints.map(joint => joint.angle);
    await page.waitForTimeout(200);
    assert.deepEqual((await state()).joints.map(joint => joint.angle), stoppedAngles);
    await page.locator('#reset').click();
    await page.waitForFunction(() => !document.body.classList.contains('stopped'));
    await page.locator('[data-scenario="curious"]').click();
    await page.waitForFunction(() => document.querySelector('#expression-name').textContent === '驚き');
    assert.equal((await state()).sensors.distanceMm, 80);
    await page.locator('#reset').click();
    await page.waitForTimeout(120);
    await page.locator('#record').click();
    await page.waitForFunction(() => document.querySelector('#record').textContent.includes('終える'));
    await page.locator('[data-expression="wink"]').click();
    await page.waitForTimeout(600);
    await changeRange('gaze-x', -6);
    await page.waitForTimeout(200);
    await page.locator('#record').click();
    await page.waitForFunction(() => document.querySelector('#record').textContent.includes('始める'));
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    const recordingFile = path.join(outputs, 'simulator-recording.json');
    await download.saveAs(recordingFile);
    const recording = JSON.parse(fs.readFileSync(recordingFile, 'utf8'));
    assert.equal(recording.schemaVersion, 1);
    assert.ok(recording.commands.some(entry => entry.command.type === 'expression' && entry.command.value === 'wink'));
    await page.locator('#reset').click();
    await page.waitForTimeout(150);
    await page.locator('#recording-file').setInputFiles(recordingFile);
    await page.waitForTimeout(recording.durationMs + 450);
    assert.equal((await state()).expression, 'wink');
    assert.equal((await state()).motion.gazeX, -6);
    await page.reload();
    await page.waitForSelector('#connection.online');
    await page.waitForFunction(() => document.querySelector('#expression-name').textContent === 'ウインク');
    assert.equal(await page.locator('#gaze-x').inputValue(), '-6', 'Reload must reflect shared runtime state.');
    await command({ type: 'reset' });
    await page.waitForTimeout(150);
    await page.locator('.pwm-details').evaluate(element => { element.open = true; });
    for (const width of [320, 760, 1440]) {
      await page.setViewportSize({ width, height: 1050 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No horizontal overflow at ${width}px.`);
      assert.ok(await page.locator('#screen').evaluate(element => { const r = element.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; }), `Display is fully visible at ${width}px.`);
    }
    await page.locator('.pwm-details').evaluate(element => { element.open = false; });
    await page.setViewportSize({ width: 1440, height: 1050 });
    fs.mkdirSync(path.join(root, 'artifacts'), { recursive: true });
    await page.screenshot({ path: path.join(root, 'artifacts', 'simulator.png'), fullPage: true });
    await page.setViewportSize({ width: 320, height: 1050 });
    await page.screenshot({ path: path.join(outputs, 'simulator-mobile.png'), fullPage: true });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#pause').textContent === '再生');
    assert.equal((await state()).paused, true);
    await close();
    await page.waitForSelector('#connection.offline', { timeout: 10000 });
    assert.equal(await page.locator('[data-expression="happy"]').isDisabled(), true);
    assert.equal(await page.locator('#pause').isDisabled(), true);
    assert.equal(await rotary.getByRole('button',{name:'Rotate clockwise',exact:true}).isDisabled(),true);
    assert.match(await page.locator('#run-status').textContent(), /最後/);
    assert.deepEqual(errors, []);
    console.log('PASS: display + shared servo wiring, pause/step, gaze, stop/reset, scenarios, recording/import/replay, shared reload, responsive 320/760/1440, reduced motion, connection loss.');
  } finally {
    await browser.close();
    if (!serverClosed) await close();
  }
})().catch(error => { console.error(error); if (!serverClosed) server.close(); process.exitCode = 1; });
